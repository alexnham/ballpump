"""Generate only the trade schemas from the checked-in official Pump IDLs."""
import json
from pathlib import Path
root = Path(__file__).resolve().parents[1]

def rust(t):
    if isinstance(t, str): return '[u8;32]' if t == 'pubkey' else 'String' if t == 'string' else t
    if 'vec' in t: return f'Vec<{rust(t["vec"])}>'
    if 'defined' in t: return t['defined']['name']
    raise ValueError(t)

out = ['// Generated by scripts/generate_decoder.py; source: docs/upstream/*.json', '#![allow(dead_code)]', 'use borsh::{BorshDeserialize, BorshSerialize};', '#[derive(Default, BorshDeserialize, BorshSerialize)] pub struct Shareholder {pub address:[u8;32], pub share_bps:u16}', '#[derive(Clone, Copy)] pub struct TradeSpec {pub disc:[u8;8], pub buy:bool, pub mint:usize, pub quote:Option<usize>, pub pool:Option<usize>}']
for venue, events in [('pump',['TradeEvent','PostCompleteBuyEvent']),('pump_amm',['BuyEvent','SellEvent','BoostBuyAndBurnEvent'])]:
    d=json.loads((root / f'docs/upstream/{venue}.json').read_text())
    out.append(f'pub const {venue.upper()}_ID: &str = "{d["address"]}";')
    for name in events:
        t=next(t for t in d['types'] if t['name']==name)
        out.append('#[derive(Default, BorshDeserialize, BorshSerialize)] pub struct '+name+'{'+''.join(f'pub {f["name"]}:{rust(f["type"])},' for f in t['type']['fields'])+'}')
        disc=next(e['discriminator'] for e in d['events'] if e['name']==name)
        out.append(f'pub const {name.upper()}_DISC: [u8;8] = {disc};')
    for instruction in d['instructions']:
        if instruction['name'].startswith('multi_hop') or instruction['name']=='boost_buy_and_burn':
            out.append(f'pub const {instruction["name"].upper()}_DISC: [u8;8] = {instruction["discriminator"]};')
    specs=[]
    for i in d['instructions']:
        if not (i['name'].startswith('buy') or i['name'].startswith('sell')): continue
        a=[a['name'] for a in i['accounts']]
        mint=a.index('mint' if 'mint' in a else 'base_mint')
        quote=f'Some({a.index("quote_mint")})' if 'quote_mint' in a else 'None'
        pool=f'Some({a.index("pool")})' if 'pool' in a else 'None'
        specs.append(f'TradeSpec{{disc:{i["discriminator"]},buy:{str(i["name"].startswith("buy")).lower()},mint:{mint},quote:{quote},pool:{pool}}}')
    out.append(f'pub const {venue.upper()}_SPECS: &[TradeSpec] = &['+','.join(specs)+'];')
(root/'backend/src/schemas.rs').write_text('\n'.join(out)+'\n')
